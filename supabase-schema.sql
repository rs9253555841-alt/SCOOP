-- 1. Create the orders table
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  name TEXT,
  phone TEXT NOT NULL,
  email TEXT,
  user_id TEXT DEFAULT 'guest',
  address TEXT NOT NULL,
  pincode TEXT,
  payment_method TEXT NOT NULL DEFAULT 'UPI',
  items JSONB NOT NULL DEFAULT '[]'::JSONB,
  subtotal NUMERIC NOT NULL DEFAULT 0,
  delivery_fee NUMERIC NOT NULL DEFAULT 0,
  discount_amount NUMERIC NOT NULL DEFAULT 0,
  discount_code TEXT,
  total NUMERIC NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'Pending',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow visitors / customers to insert orders
CREATE POLICY "Allow public insert into orders"
  ON public.orders
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

-- 4. Policy: Allow viewing orders (for confirmation and admin order views)
CREATE POLICY "Allow public select from orders"
  ON public.orders
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- 5. Policy: Allow updating orders (for updating status to Preparing / Out for Delivery / Delivered)
CREATE POLICY "Allow public update on orders"
  ON public.orders
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_order_number ON public.orders (order_number);
CREATE INDEX IF NOT EXISTS idx_orders_phone ON public.orders (phone);
